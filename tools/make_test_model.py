"""Builds the AI pipeline test model (tests/data/echo-test-lowpass).

This is NOT a voice model. It is a tiny, deterministic ONNX graph that
follows Echo's "echo.voice-model v1" I/O contract so the asynchronous
inference pipeline can be tested end to end with a real ONNX Runtime:

    audio_out = 0.5 * lowpass_fir(audio) + 0 * pitch_shift

Requires: pip install onnx numpy
Usage:    python tools/make_test_model.py
"""
import json
import math
import os

import numpy as np
import onnx
from onnx import TensorProto, helper, numpy_helper

SAMPLE_RATE = 16000
TAPS = 63
CUTOFF_HZ = 2000.0


def fir_lowpass(taps, cutoff, sr):
    m = (taps - 1) / 2.0
    fc = cutoff / sr
    h = []
    for n in range(taps):
        x = n - m
        s = 2 * fc if x == 0 else math.sin(2 * math.pi * fc * x) / (math.pi * x)
        w = 0.54 - 0.46 * math.cos(2 * math.pi * n / (taps - 1))  # Hamming
        h.append(s * w)
    g = sum(h)
    return np.array([v / g for v in h], dtype=np.float32)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_dir = os.path.join(here, "..", "tests", "data", "echo-test-lowpass")
    os.makedirs(out_dir, exist_ok=True)

    w = fir_lowpass(TAPS, CUTOFF_HZ, SAMPLE_RATE).reshape(1, 1, TAPS)
    nodes = [
        helper.make_node("Unsqueeze", ["audio", "axis1"], ["x3"]),                      # [1,1,N]
        helper.make_node("Conv", ["x3", "W"], ["y3"], pads=[TAPS // 2, TAPS // 2]),   # same length
        helper.make_node("Squeeze", ["y3", "axis1"], ["y2"]),                           # [1,N]
        helper.make_node("Mul", ["y2", "half"], ["y_scaled"]),
        helper.make_node("Mul", ["pitch_shift", "zero"], ["p0"]),
        helper.make_node("Add", ["y_scaled", "p0"], ["audio_out"]),
    ]
    inits = [
        numpy_helper.from_array(w, "W"),
        numpy_helper.from_array(np.array([1], dtype=np.int64), "axis1"),
        numpy_helper.from_array(np.array(0.5, dtype=np.float32), "half"),
        numpy_helper.from_array(np.array(0.0, dtype=np.float32), "zero"),
    ]
    graph = helper.make_graph(
        nodes,
        "echo_test_lowpass",
        [helper.make_tensor_value_info("audio", TensorProto.FLOAT, [1, "N"]),
         helper.make_tensor_value_info("pitch_shift", TensorProto.FLOAT, [1])],
        [helper.make_tensor_value_info("audio_out", TensorProto.FLOAT, [1, "N"])],
        inits,
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 13)], producer_name="echo-tools")
    model.ir_version = 8
    onnx.checker.check_model(model)
    onnx.save(model, os.path.join(out_dir, "model.onnx"))

    manifest = {
        "format": "echo.voice-model",
        "version": 1,
        "name": "Echo pipeline test (low-pass, not a voice)",
        "author": "Echo project",
        "license": "MIT",
        "source": "Generated by tools/make_test_model.py",
        "description": "Deterministic 2 kHz low-pass filter at half gain. Used to verify the asynchronous AI "
                       "inference pipeline; it does not change voice identity.",
        "consent": "Synthetic test model; contains no voice data.",
        "onnx": "model.onnx",
        "sample_rate": SAMPLE_RATE,
        "chunk_ms": 160,
        "context_ms": 80,
        "crossfade_ms": 10,
        "input": "audio",
        "output": "audio_out",
        "pitch_input": "pitch_shift",
    }
    with open(os.path.join(out_dir, "model.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print("wrote", os.path.normpath(out_dir))


if __name__ == "__main__":
    main()
